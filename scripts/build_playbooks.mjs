// Compiles the agent playbooks (supabase/functions/agents/*.md) into a module
// the edge function imports, since only code is bundled on deploy.
//   node scripts/build_playbooks.mjs          write the module
//   node scripts/build_playbooks.mjs --check  fail if it is out of date
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'supabase/functions/agents');
const out = path.join(root, 'supabase/functions/_shared/playbooks.ts');

export function render() {
  const files = readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
  const entries = files.map((f) => `  ${JSON.stringify(f.replace(/\.md$/, ''))}: ${JSON.stringify(readFileSync(path.join(dir, f), 'utf8'))},`);
  return `// Generated by scripts/build_playbooks.mjs from supabase/functions/agents/*.md. Do not edit.\nexport const PLAYBOOKS: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = readFileSync(out, 'utf8');
    if (current !== text) {
      console.error('supabase/functions/_shared/playbooks.ts is out of date: run node scripts/build_playbooks.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${path.relative(root, out)}`);
  }
}
