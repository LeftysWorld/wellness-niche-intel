def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def j(v):
    return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"


def arr(xs):
    return "array[" + ",".join(q(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"


def tri(low, mode, high):
    return {"low": low, "mode": mode, "high": high}


def pt(v):
    return tri(v, v, v)


def per_acre_from_cop(cop, m2):
    return round(cop / COP_PER_USD / (m2 / M2_PER_ACRE))


